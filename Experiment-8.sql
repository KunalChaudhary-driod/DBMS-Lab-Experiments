-- 1. CREATE THE BANK TABLE

CREATE TABLE Bank (
    account_id INT PRIMARY KEY,
    account_name VARCHAR(50),
    balance DECIMAL(10,2)
);

INSERT INTO Bank VALUES
(1, 'Yusuf', 10000),
(2, 'Amit', 5000);


-- 2. BEGIN AND COMMIT
-- Transfer 1000 from account 1 to account 2.

START TRANSACTION;

UPDATE Bank
SET balance = balance - 1000
WHERE account_id = 1;

UPDATE Bank
SET balance = balance + 1000
WHERE account_id = 2;

COMMIT;

SELECT * FROM Bank;


-- 3. ROLLBACK

START TRANSACTION;

UPDATE Bank
SET balance = balance - 2000
WHERE account_id = 1;

ROLLBACK;

SELECT * FROM Bank;


-- 4. SAVEPOINT

START TRANSACTION;

UPDATE Bank
SET balance = balance - 500
WHERE account_id = 1;

SAVEPOINT sp1;

UPDATE Bank
SET balance = balance + 500
WHERE account_id = 2;

ROLLBACK TO sp1;

COMMIT;

SELECT * FROM Bank;


-- 5. SIMULATE AN INSUFFICIENT-BALANCE FAILURE

START TRANSACTION;

UPDATE Bank
SET balance = balance - 20000
WHERE account_id = 1
AND balance >= 20000;

SELECT ROW_COUNT() AS rows_updated;

ROLLBACK;


-- 6. DEMONSTRATE ISOLATION LEVELS

SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED;

START TRANSACTION;

SELECT * FROM Bank;

COMMIT;


-- Other supported isolation levels in MySQL
-- Run one isolation level at a time.

SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ;

SET SESSION TRANSACTION ISOLATION LEVEL SERIALIZABLE;


-- 7. DEMONSTRATE CONCURRENCY USING TWO SESSIONS

-- SESSION A

SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED;

START TRANSACTION;

SELECT balance
FROM Bank
WHERE account_id = 1;

UPDATE Bank
SET balance = balance - 500
WHERE account_id = 1;

COMMIT;


-- SESSION B

SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED;

START TRANSACTION;

SELECT balance
FROM Bank
WHERE account_id = 1;

COMMIT;


-- 8. DEMONSTRATE REPEATABLE READ
-- Execute in SESSION B.

SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ;

START TRANSACTION;

SELECT balance
FROM Bank
WHERE account_id = 1;

SELECT balance
FROM Bank
WHERE account_id = 1;

COMMIT;


-- 9. DEMONSTRATE A DIRTY READ
-- Execute in SESSION B.

SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

START TRANSACTION;

SELECT balance
FROM Bank
WHERE account_id = 1;

COMMIT;
